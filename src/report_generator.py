"""
Module: report_generator.py
Description: Generates structured, downloadable academic analysis reports
documenting the Mathematical Morphological Reconstruction (MMR) analysis,
algorithm parameters, quantitative region properties, and research disclaimers.
"""

from typing import Dict, Any, Optional
import datetime
import pandas as pd


def generate_markdown_report(
    filename: str,
    image_shape: tuple,
    processing_time_sec: float,
    prep_params: Dict[str, Any],
    mmr_params: Dict[str, Any],
    seg_params: Dict[str, Any],
    feature_df: pd.DataFrame,
    eval_metrics: Optional[Dict[str, Any]] = None
) -> str:
    """
    Creates a comprehensive academic Markdown analysis report.
    """
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    num_regions = len(feature_df)
    total_area = int(feature_df["Area_Pixels"].sum()) if num_regions > 0 else 0

    lines = []
    lines.append("# Brain MRI Analysis Report: Mathematical Morphological Reconstruction (MMR)")
    lines.append(f"**Generated:** {timestamp}")
    lines.append("")
    lines.append("> [!IMPORTANT]")
    lines.append("> **ACADEMIC RESEARCH & EDUCATIONAL PROTOTYPE ONLY**")
    lines.append("> This report was generated by an automated morphological image processing algorithm.")
    lines.append("> It does **NOT** constitute clinical advice, medical diagnosis, or patient management recommendations.")
    lines.append("> All segmented structures are labeled strictly as *candidate abnormal regions*.")
    lines.append("")

    lines.append("## 1. Input Specification")
    lines.append(f"- **Source Image:** `{filename}`")
    lines.append(f"- **Dimensions:** {image_shape[0]} × {image_shape[1]} pixels")
    lines.append(f"- **Execution Duration:** {processing_time_sec:.4f} seconds")
    lines.append("")

    lines.append("## 2. Algorithmic Pipeline & Parameters")
    lines.append("### Preprocessing")
    lines.append(f"- Gaussian Noise Filter: `{'Enabled' if prep_params.get('enable_denoise') else 'Disabled'}` (sigma = {prep_params.get('gaussian_sigma', 'N/A')})")
    lines.append(f"- Contrast Enhancement (CLAHE): `{'Enabled' if prep_params.get('enable_clahe') else 'Disabled'}` (clip limit = {prep_params.get('clahe_clip_limit', 'N/A')}, grid = {prep_params.get('clahe_tile_grid', 'N/A')})")
    lines.append("")

    lines.append("### Mathematical Morphological Reconstruction")
    lines.append(f"- Strategy: `{mmr_params.get('method', 'opening_by_reconstruction')}`")
    lines.append(f"- Reconstruction Mode: `{mmr_params.get('recon_mode', 'dilation')}`")
    lines.append(f"- Structuring Element: `{mmr_params.get('selem_shape', 'disk')}` (size/radius = {mmr_params.get('selem_size', 5)})")
    if mmr_params.get("h_param"):
        lines.append(f"- H-Dome Parameter: `{mmr_params.get('h_param')}`")
    lines.append(f"- Theoretical Principle: {mmr_params.get('strategy_description', 'Iterative geodesic dilation under mask constraint.')}")
    lines.append("")

    lines.append("### Candidate Region Segmentation")
    lines.append(f"- Thresholding Strategy: `{seg_params.get('method', 'otsu')}`")
    lines.append(f"- Minimum Component Area: `{seg_params.get('min_area', 80)}` pixels")
    lines.append(f"- Opening Radius: `{seg_params.get('opening_radius', 2)}` px | Closing Radius: `{seg_params.get('closing_radius', 3)}` px")
    lines.append(f"- Interior Cavity Filling: `{'Enabled' if seg_params.get('fill_holes') else 'Disabled'}`")
    lines.append("")

    lines.append("## 3. Candidate Region Findings")
    if num_regions == 0:
        lines.append("**No candidate abnormal regions were detected** under the current parameter threshold.")
        lines.append("This is consistent with normal healthy tissue or sub-threshold contrast gradients.")
    else:
        lines.append(f"- **Total Detected Candidate Regions:** {num_regions}")
        lines.append(f"- **Cumulative Candidate Area:** {total_area} pixels")
        lines.append("")
        lines.append("### Morphological Measurements Table")
        try:
            lines.append(feature_df.to_markdown(index=False))
        except Exception:
            # Fallback pure-Python markdown table formatting
            headers = [str(c) for c in feature_df.columns]
            header_line = "| " + " | ".join(headers) + " |"
            sep_line = "| " + " | ".join(["---"] * len(headers)) + " |"
            row_lines = []
            for _, row in feature_df.iterrows():
                row_lines.append("| " + " | ".join(str(val) for val in row.values) + " |")
            lines.append("\n".join([header_line, sep_line] + row_lines))
    lines.append("")

    if eval_metrics is not None:
        lines.append("## 4. Quantitative Ground-Truth Validation")
        lines.append("| Metric | Measured Value | Interpretation |")
        lines.append("|---|---|---|")
        lines.append(f"| **Dice Similarity Coefficient (DSC)** | `{eval_metrics['dice_coefficient']:.4f}` | Spatial overlap relative to reference mask |")
        lines.append(f"| **Intersection over Union (IoU)** | `{eval_metrics['iou_jaccard']:.4f}` | Jaccard index |")
        lines.append(f"| **Sensitivity (Recall)** | `{eval_metrics['sensitivity']:.4f}` | Fraction of reference lesion successfully detected |")
        lines.append(f"| **Specificity** | `{eval_metrics['specificity']:.4f}` | True negative background retention |")
        lines.append(f"| **Precision** | `{eval_metrics['precision']:.4f}` | Fraction of candidate region that is true lesion |")
        lines.append("")

    lines.append("## 5. Methodological Limitations")
    lines.append("1. **Intensity-Contrast Dependency:** MMR identifies regions based on geometric intensity plateaus relative to surrounding parenchyma. Contrast variation across scanners and sequences (T1, T2, FLAIR) affects segmentation.")
    lines.append("2. **Normal Hyperintense Mimics:** Hyperintense anatomical structures (e.g. choroid plexus, fat tissue, large vessels) may produce residual peaks unless filtered by intracranial masking.")
    lines.append("3. **Non-Diagnostic:** Morphological segmentation does not assess histological grade, molecular subtypes, or tumor viability.")
    lines.append("")
    lines.append("---")
    lines.append("*Report generated by Academic Image Processing Prototype: MMR Brain MRI Analysis.*")

    return "\n".join(lines)


def generate_csv_bytes(feature_df: pd.DataFrame) -> bytes:
    """
    Encodes feature dataframe to UTF-8 CSV bytes.
    """
    return feature_df.to_csv(index=False).encode("utf-8")
